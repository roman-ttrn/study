#!/bin/bash
# Отключает вывод выполняемых команд на экран. Без этого каждая строка скрипта
# печаталась бы в консоль перед выполнением, и было бы грязно.
# (В bash по умолчанию команды и так не печатаются, поэтому аналог @echo off не нужен.
#  Если хочется явно — можно вставить `set +x`, но это лишнее.)

# chcp 1251 > log
# «change code page», меняет кодировку консоли. 1251 — кодировка Windows для кириллицы.
# В Linux/macOS везде UTF-8, менять кодировку не нужно. Эти строки пропускаем.

# del log
# Удаление временного лога. В Linux/macOS не нужно, потому что chcp нет.

CPP_FILES="io.cpp sortings.cpp main.cpp"
# Создаёт переменную CPP_FILES, в которой лежит список исходных файлов C++.
# Дальше можно использовать $CPP_FILES, чтобы не писать их заново.

EXE="my_correct_sort"
# Переменная EXE — имя итогового исполняемого файла, который получится после компиляции.
# В Linux/macOS расширение .exe не используется.

CHARSET="-finput-charset=utf-8 -fexec-charset=utf-8"
# -finput-charset=utf-8 — .cpp файлы сохранены в UTF-8, компилятор читает их как UTF-8.
# -fexec-charset=utf-8 — строковые литералы внутри программы тоже в UTF-8,
#                        чтобы корректно отображаться в консоли Linux/macOS.
# (На Windows было windows-1251, здесь всё в UTF-8.)

if [ -f "$EXE" ]; then
    rm "$EXE"
fi
# Если файл my_correct_sort уже существует от прошлой сборки — удалить его.
# Это чтобы не запустить случайно старую версию, если компиляция упадёт с ошибкой.
# [ -f "$EXE" ] — «файл существует». rm — удаление.

g++ $CHARSET $CPP_FILES -o $EXE
# Компиляция.
# $CHARSET → флаги кодировки.
# $CPP_FILES → список исходников.
# -o $EXE → имя выходного файла.

./$EXE
# Запускаем файл. Обрати внимание на ./
# Без ./, bash будет искать программу в системных путях (PATH) и не найдёт её.
# ./$EXE = «запусти файл my_correct_sort из текущей папки».